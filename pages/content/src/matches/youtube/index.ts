import { extractYouTubeMedia, hasDirectAdaptiveVideo } from './player-formats';
import { createLogger, MEDIA_MESSAGE } from '@extension/shared';
import { createBridge, onFromMain, sendToMain } from '@src/lib/broadcast-bridge';
import type { MediaVariant, SubtitleTrack } from '@extension/shared';

const sentUrls = new Set<string>();
const log = createLogger('youtube');
const attemptedInnertubeVideoIds = new Set<string>();

const ANDROID_VR_CLIENT_NAME = 'ANDROID_VR';
const ANDROID_VR_CLIENT_VERSION = '1.65.10';
const ANDROID_VR_CLIENT_ID = '28';
const ANDROID_VR_USER_AGENT =
  'com.google.android.apps.youtube.vr.oculus/1.65.10 (Linux; U; Android 12L; eureka-user Build/SQ3A.220605.009.A1) gzip';

type YTFormat = {
  itag?: number;
  url?: string;
  signatureCipher?: string;
  mimeType?: string;
  qualityLabel?: string;
  width?: number;
  height?: number;
  fps?: number;
  contentLength?: string;
  audioQuality?: string;
  bitrate?: number;
};

type StreamingData = {
  formats?: YTFormat[];
  adaptiveFormats?: YTFormat[];
  hlsManifestUrl?: string;
  dashManifestUrl?: string;
};

type YTCaptionTrack = {
  baseUrl?: string;
  languageCode?: string;
  kind?: string;
  name?: { simpleText?: string };
};

type PlayerResponse = {
  streamingData?: StreamingData;
  videoDetails?: { title?: string; lengthSeconds?: string };
  playabilityStatus?: { status?: string; reason?: string };
  captions?: {
    playerCaptionsTracklistRenderer?: {
      captionTracks?: YTCaptionTrack[];
    };
  };
};

type YtConfig = {
  INNERTUBE_API_KEY?: string;
  VISITOR_DATA?: string;
  HL?: string;
};

const readYtConfig = (): YtConfig => {
  const out: YtConfig = {};
  const html = document.documentElement.innerHTML;
  const read = (key: keyof YtConfig) => {
    const match = html.match(new RegExp(`"${key}"\\s*:\\s*"([^"]+)"`));
    if (match?.[1]) out[key] = JSON.parse(`"${match[1]}"`) as string;
  };
  read('INNERTUBE_API_KEY');
  read('VISITOR_DATA');
  read('HL');
  return out;
};

const getVideoId = () => {
  const fromQuery = new URL(location.href).searchParams.get('v');
  if (fromQuery) return fromQuery;
  const shortsMatch = location.pathname.match(/^\/shorts\/([^/?#]+)/);
  return shortsMatch?.[1];
};

const extractCaptionTracks = (pr: PlayerResponse): SubtitleTrack[] => {
  const tracks = pr.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
  const out: SubtitleTrack[] = [];
  for (const t of tracks) {
    if (!t.baseUrl || !t.languageCode) continue;
    const url = new URL(t.baseUrl);
    url.searchParams.set('fmt', 'vtt');
    out.push({
      url: url.toString(),
      language: t.languageCode,
      label: t.name?.simpleText,
      format: 'vtt',
      isAutoGenerated: t.kind === 'asr',
    });
  }
  return out;
};

const sendCandidate = (candidate: {
  url: string;
  kind: 'video' | 'audio' | 'hls' | 'dash';
  mimeType?: string;
  title?: string;
  resolution?: { width: number; height: number };
  contentLength?: number;
  audioUrl?: string;
  audioMimeType?: string;
  subtitles?: SubtitleTrack[];
  variants?: MediaVariant[];
}) => {
  if (!candidate.url || sentUrls.has(candidate.url)) return false;
  sentUrls.add(candidate.url);
  log.debug('candidate', {
    kind: candidate.kind,
    mimeType: candidate.mimeType,
    resolution: candidate.resolution,
    contentLength: candidate.contentLength,
    hasAudio: Boolean(candidate.audioUrl),
    variantCount: candidate.variants?.length ?? 0,
  });
  chrome.runtime
    .sendMessage({
      type: MEDIA_MESSAGE.DETECTED,
      payload: {
        url: candidate.url,
        mimeType: candidate.mimeType,
        kind: candidate.kind,
        source: 'element' as const,
        title: candidate.title ?? document.title.replace(/\s*-\s*YouTube$/, ''),
        resolution: candidate.resolution,
        contentLength: candidate.contentLength,
        audioUrl: candidate.audioUrl,
        audioMimeType: candidate.audioMimeType,
        subtitles: candidate.subtitles,
        variants: candidate.variants,
      },
    })
    .then(response => log.debug('candidate.sent', { response }))
    .catch(error => log.warn('candidate.send_failed', { error }));
  return true;
};

const extractFormats = (pr: PlayerResponse) => {
  const { streamingData, videoDetails } = pr;
  if (!streamingData) {
    log.warn('player.no_streaming_data');
    return 0;
  }

  const allFormats = [...(streamingData.formats ?? []), ...(streamingData.adaptiveFormats ?? [])];
  log.debug('player.formats', {
    progressiveCount: streamingData.formats?.length ?? 0,
    adaptiveCount: streamingData.adaptiveFormats?.length ?? 0,
    directVideoCount: allFormats.filter(format => !!format.url && format.mimeType?.startsWith('video/')).length,
    encryptedVideoCount: allFormats.filter(format => !!format.signatureCipher && format.mimeType?.startsWith('video/'))
      .length,
    directAdaptiveVideo: hasDirectAdaptiveVideo(pr),
  });

  const rawTitle = videoDetails?.title ?? document.title;
  const title = rawTitle.replace(/\s*-\s*YouTube$/, '');
  const subtitles = extractCaptionTracks(pr);
  const subs = subtitles.length > 0 ? subtitles : undefined;
  let sentCount = 0;

  if (streamingData.hlsManifestUrl) {
    if (sendCandidate({ url: streamingData.hlsManifestUrl, kind: 'hls', title, subtitles: subs })) sentCount += 1;
    return sentCount;
  }

  if (streamingData.dashManifestUrl) {
    if (sendCandidate({ url: streamingData.dashManifestUrl, kind: 'dash', title, subtitles: subs })) sentCount += 1;
    return sentCount;
  }

  const media = extractYouTubeMedia(pr);
  const primary = media?.primary;

  if (primary?.url && media) {
    log.debug('player.variants', {
      variants: media.variants.map(variant => ({
        resolution: variant.resolution,
        name: variant.name,
        frameRate: variant.frameRate,
        mimeType: variant.mimeType,
        hasAudio: Boolean(variant.audioUrl),
      })),
    });
    const primaryVariant = media.variants.find(variant => variant.url === primary.url);
    if (
      sendCandidate({
        url: primary.url,
        kind: 'video',
        mimeType: primary.mimeType,
        title,
        resolution: primary.width && primary.height ? { width: primary.width, height: primary.height } : undefined,
        contentLength: primary.contentLength ? Number(primary.contentLength) : undefined,
        audioUrl: primaryVariant?.audioUrl,
        audioMimeType: primaryVariant?.audioMimeType,
        subtitles: subs,
        variants: media.variants,
      })
    )
      sentCount += 1;
  }

  return sentCount;
};

const fetchAndroidVrPlayerResponse = async (videoId: string): Promise<PlayerResponse | undefined> => {
  const cfg = readYtConfig();
  if (!cfg.INNERTUBE_API_KEY) return undefined;

  const visitorData = cfg.VISITOR_DATA;
  const timeZone = Intl.DateTimeFormat().resolvedOptions().timeZone || 'UTC';
  const utcOffsetMinutes = -new Date().getTimezoneOffset();

  const res = await fetch(
    `https://www.youtube.com/youtubei/v1/player?${new URLSearchParams({
      prettyPrint: 'false',
      key: cfg.INNERTUBE_API_KEY,
    })}`,
    {
      method: 'POST',
      credentials: 'include',
      headers: {
        'Content-Type': 'application/json',
        'X-Youtube-Client-Name': ANDROID_VR_CLIENT_ID,
        'X-Youtube-Client-Version': ANDROID_VR_CLIENT_VERSION,
        ...(visitorData ? { 'X-Goog-Visitor-Id': visitorData } : {}),
      },
      body: JSON.stringify({
        context: {
          client: {
            clientName: ANDROID_VR_CLIENT_NAME,
            clientVersion: ANDROID_VR_CLIENT_VERSION,
            deviceMake: 'Oculus',
            deviceModel: 'Quest 3',
            androidSdkVersion: 32,
            userAgent: ANDROID_VR_USER_AGENT,
            osName: 'Android',
            osVersion: '12L',
            hl: cfg.HL ?? 'en',
            timeZone,
            utcOffsetMinutes,
            ...(visitorData ? { visitorData } : {}),
          },
        },
        videoId,
        contentCheckOk: true,
        racyCheckOk: true,
        playbackContext: {
          contentPlaybackContext: {
            html5Preference: 'HTML5_PREF_WANTS',
          },
        },
      }),
    },
  );

  if (!res.ok) return undefined;
  const pr = (await res.json()) as PlayerResponse;
  if (pr.playabilityStatus?.status && pr.playabilityStatus.status !== 'OK') return undefined;
  return pr;
};

const tryAndroidVrFallback = async () => {
  const videoId = getVideoId();
  if (!videoId || attemptedInnertubeVideoIds.has(videoId)) return;
  attemptedInnertubeVideoIds.add(videoId);
  log.debug('android_vr.start', { videoId });

  try {
    const pr = await fetchAndroidVrPlayerResponse(videoId);
    if (pr?.streamingData) {
      log.debug('android_vr.response', { hasStreamingData: true });
      extractFormats(pr);
    } else {
      log.warn('android_vr.no_media');
    }
  } catch (error) {
    log.warn('android_vr.failed', { error });
    // The page-level WEB response is still handled above; this fallback is best-effort.
  }
};

const extractFromScriptTag = (): number | undefined => {
  for (const script of Array.from(document.querySelectorAll('script'))) {
    const text = script.textContent ?? '';
    const match =
      text.match(/ytInitialPlayerResponse\s*=\s*(\{.+?\})(?:;|,|\n)/s) ??
      text.match(/ytInitialPlayerResponse":\s*(\{.+?\})(?:,|\})/s);
    if (match?.[1]) {
      try {
        const pr = JSON.parse(match[1]) as PlayerResponse;
        if (pr?.streamingData) {
          return extractFormats(pr);
        }
      } catch {
        continue;
      }
    }
  }
  return undefined;
};

export const startYouTubeContentScript = (): void => {
  let mainWorldRelayReceived = false;
  const bridge = createBridge(window.location.href);

  onFromMain(bridge, msg => {
    if (msg.name === 'youtube_player_response') {
      const pr = (msg.data as { playerResponse?: PlayerResponse })?.playerResponse;
      if (pr?.streamingData) {
        mainWorldRelayReceived = true;
        const sentCount = extractFormats(pr);
        if (sentCount === 0 || !hasDirectAdaptiveVideo(pr)) void tryAndroidVrFallback();
      }
    }
  });

  const tryExtract = async () => {
    sendToMain(bridge, { name: 'youtube_request_player_response', data: null });
    setTimeout(() => {
      if (!mainWorldRelayReceived) {
        const sentCount = extractFromScriptTag();
        if (!sentCount) void tryAndroidVrFallback();
      }
      if (mainWorldRelayReceived && sentUrls.size === 0) void tryAndroidVrFallback();
    }, 300);
  };

  sendToMain(bridge, { name: 'youtube_request_player_response', data: null });

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => setTimeout(tryExtract, 800));
  } else {
    setTimeout(tryExtract, 800);
  }

  document.addEventListener('yt-navigate-finish', () => {
    sentUrls.clear();
    attemptedInnertubeVideoIds.clear();
    mainWorldRelayReceived = false;
    setTimeout(() => void tryExtract(), 1200);
  });

  let lastUrl = location.href;
  new MutationObserver(() => {
    if (location.href !== lastUrl) {
      lastUrl = location.href;
      sentUrls.clear();
      attemptedInnertubeVideoIds.clear();
      mainWorldRelayReceived = false;
      setTimeout(() => void tryExtract(), 1200);
    }
  }).observe(document.documentElement, { childList: true, subtree: true });
};
