-- UUGet billing schema (M1).
--
-- Money is integer cents; credit deltas are integer credits. Balances are
-- derived from credit_ledger (append-only), never stored as a mutable column.
-- Free-quota and credit reservations are enforced by triggers so a single
-- INSERT statement is atomic under D1's serialized write path.

PRAGMA foreign_keys = ON;

CREATE TABLE accounts (
  id TEXT PRIMARY KEY,                 -- acc_<uuid>
  email TEXT NOT NULL UNIQUE,          -- lower-case, from Creem customer.email
  creem_customer_id TEXT UNIQUE,
  created_at INTEGER NOT NULL,
  deleted_at INTEGER
);

CREATE TABLE devices (
  id TEXT PRIMARY KEY,                 -- dev_<uuid>, generated by extension
  token_hash TEXT NOT NULL UNIQUE,     -- SHA-256(base64url deviceToken), hex
  account_id TEXT REFERENCES accounts(id),
  name TEXT,
  created_at INTEGER NOT NULL,
  last_seen_at INTEGER NOT NULL,
  revoked_at INTEGER
);

CREATE TABLE purchases (
  id TEXT PRIMARY KEY,                 -- Creem order id, idempotency key
  account_id TEXT NOT NULL REFERENCES accounts(id),
  product_id TEXT NOT NULL,
  product_key TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('credits','subscription')),
  credits INTEGER NOT NULL DEFAULT 0,
  amount_cents INTEGER NOT NULL,
  currency TEXT NOT NULL,
  created_at INTEGER NOT NULL
);

CREATE TABLE credit_ledger (
  id TEXT PRIMARY KEY,
  account_id TEXT NOT NULL REFERENCES accounts(id),
  delta INTEGER NOT NULL,              -- +grant, -reserve, +release, -chargeback
  reason TEXT NOT NULL CHECK (reason IN ('grant','reserve','release','chargeback','adjust')),
  ref TEXT NOT NULL,                   -- grant:<order_id> / reserve:<auth_id> / ...
  created_at INTEGER NOT NULL,
  UNIQUE (account_id, ref)
);

CREATE TABLE daily_usage (
  device_id TEXT NOT NULL REFERENCES devices(id),
  utc_date TEXT NOT NULL,              -- YYYY-MM-DD
  used INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (device_id, utc_date)
);

CREATE TABLE authorizations (
  id TEXT PRIMARY KEY,                 -- auth_<uuid>
  device_id TEXT NOT NULL REFERENCES devices(id),
  account_id TEXT REFERENCES accounts(id),
  download_key TEXT NOT NULL,
  source TEXT NOT NULL CHECK (source IN ('free','subscription','credits')),
  state TEXT NOT NULL CHECK (state IN ('reserved','committed','released')),
  credits_reserved INTEGER NOT NULL DEFAULT 0,
  free_reserved INTEGER NOT NULL DEFAULT 0,
  created_at INTEGER NOT NULL,         -- start of the current reservation cycle
  updated_at INTEGER NOT NULL,
  UNIQUE (device_id, download_key)
);

CREATE TABLE subscriptions (
  id TEXT PRIMARY KEY,                 -- Creem subscription id
  account_id TEXT NOT NULL REFERENCES accounts(id),
  product_id TEXT NOT NULL,
  status TEXT NOT NULL,                -- active/trialing/canceled/expired/paused
  current_period_end INTEGER,
  cancel_at_period_end INTEGER NOT NULL DEFAULT 0,
  updated_at INTEGER NOT NULL
);

CREATE TABLE license_keys (
  key_hash TEXT PRIMARY KEY,           -- SHA-256(normalized key)
  key_last4 TEXT NOT NULL,
  account_id TEXT REFERENCES accounts(id),
  product_id TEXT NOT NULL,
  activation_limit INTEGER,
  status TEXT NOT NULL,
  expires_at INTEGER,
  created_at INTEGER NOT NULL
);

CREATE TABLE webhook_events (
  id TEXT PRIMARY KEY,                 -- Creem event id
  type TEXT NOT NULL,
  received_at INTEGER NOT NULL
);

-- Runtime knobs shared by the Worker and the quota triggers.
CREATE TABLE settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL,
  updated_at INTEGER NOT NULL
);

-- Fixed-window rate limiting: bucket already contains the window start so a
-- new window starts counting from zero without a cleanup race.
CREATE TABLE rate_limits (
  bucket TEXT PRIMARY KEY,
  window_start INTEGER NOT NULL,
  count INTEGER NOT NULL
);

INSERT INTO settings (key, value, updated_at) VALUES
  ('free_daily_limit', '2', 0),
  ('billing_enforcement', 'on', 0);

CREATE INDEX idx_devices_account ON devices (account_id);
CREATE INDEX idx_authorizations_device ON authorizations (device_id, created_at);
CREATE INDEX idx_authorizations_state ON authorizations (state, updated_at);
CREATE INDEX idx_credit_ledger_account ON credit_ledger (account_id);
CREATE INDEX idx_daily_usage_date ON daily_usage (utc_date);
CREATE INDEX idx_subscriptions_account ON subscriptions (account_id, updated_at);
CREATE INDEX idx_rate_limits_window ON rate_limits (window_start);

-- ---------------------------------------------------------------------------
-- Reservation guards (INSERT)
-- ---------------------------------------------------------------------------

-- Free quota: atomically claim one slot for the UTC day of created_at. When the
-- row already hit the limit the upsert changes zero rows and the statement is
-- aborted, rolling back the authorization insert.
CREATE TRIGGER authorizations_free_guard
BEFORE INSERT ON authorizations
WHEN NEW.source = 'free' AND NEW.free_reserved > 0
BEGIN
  INSERT INTO daily_usage (device_id, utc_date, used)
  VALUES (NEW.device_id, strftime('%Y-%m-%d', NEW.created_at / 1000, 'unixepoch'), 1)
  ON CONFLICT(device_id, utc_date) DO UPDATE SET used = used + 1
    WHERE used < COALESCE((SELECT CAST(value AS INTEGER) FROM settings WHERE key = 'free_daily_limit'), 2);
  SELECT CASE WHEN changes() = 0 THEN RAISE(ABORT, 'free_quota_exhausted') END;
END;

-- Credits: append a -N reserve row only when the derived balance covers it.
CREATE TRIGGER authorizations_credits_guard
BEFORE INSERT ON authorizations
WHEN NEW.source = 'credits' AND NEW.credits_reserved > 0
BEGIN
  INSERT INTO credit_ledger (id, account_id, delta, reason, ref, created_at)
  SELECT 'reserve:' || NEW.id, NEW.account_id, -NEW.credits_reserved, 'reserve', 'reserve:' || NEW.id, NEW.created_at
  WHERE NEW.account_id IS NOT NULL
    AND (SELECT COALESCE(SUM(delta), 0) FROM credit_ledger WHERE account_id = NEW.account_id) >= NEW.credits_reserved;
  SELECT CASE WHEN changes() = 0 THEN RAISE(ABORT, 'insufficient_credits') END;
END;

-- ---------------------------------------------------------------------------
-- Re-reservation after release (retry with the same downloadKey)
-- ---------------------------------------------------------------------------

-- A retry starts a new reservation cycle: created_at moves to the retry time so
-- the free slot is claimed against the current UTC day. The ref suffix keeps
-- the append-only ledger unique across repeated reserve/release cycles.
CREATE TRIGGER authorizations_rereserve_free_guard
AFTER UPDATE OF state ON authorizations
WHEN OLD.state = 'released' AND NEW.state = 'reserved'
  AND NEW.source = 'free' AND NEW.free_reserved > 0
BEGIN
  INSERT INTO daily_usage (device_id, utc_date, used)
  VALUES (NEW.device_id, strftime('%Y-%m-%d', NEW.created_at / 1000, 'unixepoch'), 1)
  ON CONFLICT(device_id, utc_date) DO UPDATE SET used = used + 1
    WHERE used < COALESCE((SELECT CAST(value AS INTEGER) FROM settings WHERE key = 'free_daily_limit'), 2);
  SELECT CASE WHEN changes() = 0 THEN RAISE(ABORT, 'free_quota_exhausted') END;
END;

CREATE TRIGGER authorizations_rereserve_credits_guard
AFTER UPDATE OF state ON authorizations
WHEN OLD.state = 'released' AND NEW.state = 'reserved'
  AND NEW.source = 'credits' AND NEW.credits_reserved > 0
BEGIN
  INSERT INTO credit_ledger (id, account_id, delta, reason, ref, created_at)
  SELECT 'reserve:' || NEW.id || ':' || NEW.updated_at, NEW.account_id, -NEW.credits_reserved,
         'reserve', 'reserve:' || NEW.id || ':' || NEW.updated_at, NEW.updated_at
  WHERE NEW.account_id IS NOT NULL
    AND (SELECT COALESCE(SUM(delta), 0) FROM credit_ledger WHERE account_id = NEW.account_id) >= NEW.credits_reserved;
  SELECT CASE WHEN changes() = 0 THEN RAISE(ABORT, 'insufficient_credits') END;
END;

-- ---------------------------------------------------------------------------
-- Release refunds
-- ---------------------------------------------------------------------------

-- Reached only when the UPDATE transitions reserved -> released, so duplicate
-- reports cannot refund twice. Refund the free slot on the reservation day and
-- append a +N release row for credits.
CREATE TRIGGER authorizations_release_effects
AFTER UPDATE OF state ON authorizations
WHEN OLD.state = 'reserved' AND NEW.state = 'released'
BEGIN
  UPDATE daily_usage SET used = MAX(0, used - 1)
  WHERE device_id = NEW.device_id
    AND utc_date = strftime('%Y-%m-%d', NEW.created_at / 1000, 'unixepoch')
    AND NEW.free_reserved > 0;

  INSERT INTO credit_ledger (id, account_id, delta, reason, ref, created_at)
  SELECT 'release:' || NEW.id || ':' || NEW.updated_at, NEW.account_id, NEW.credits_reserved,
         'release', 'release:' || NEW.id || ':' || NEW.updated_at, NEW.updated_at
  WHERE NEW.credits_reserved > 0 AND NEW.account_id IS NOT NULL;
END;
